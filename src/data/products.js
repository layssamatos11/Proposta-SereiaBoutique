export function getCategory(slug) {
  return categories.find((category) => category.slug === slug);
}

export function getProduct(id) {
  return products.find((product) => product.id === id);
}

export function productsIn(slug) {
  if (!slug || slug === "tudo") return products;
  if (slug === "promocoes") return products.filter((product) => product.promo);
  return products.filter((product) => product.categories.includes(slug));
}

export function relatedProducts(product, limit = 4) {
  const same = products.filter(
    (item) => item.id !== product.id && item.categories.some((slug) => product.categories.includes(slug)),
  );
  const rest = products.filter((item) => item.id !== product.id && !same.includes(item));
  return [...same, ...rest].slice(0, limit);
}
